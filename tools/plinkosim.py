#!/usr/bin/env python3
"""Plinko: 12 rows, the ball lands in slot k with probability C(12,k)/2^12. Exact RTP per risk
table; --write scales each table to TARGET (keeping the edges' shape) into qml/js/PlinkoConfig.js."""
import json, sys
from math import comb
TARGET = 0.97
ROWS = 12
SHAPES = {   # slot 0..12, symmetric; relative shape (rescaled below)
    "low":    [10, 3, 1.6, 1.4, 1.1, 1.0, 0.5, 1.0, 1.1, 1.4, 1.6, 3, 10],
    "medium": [33, 11, 4, 2, 1.1, 0.6, 0.3, 0.6, 1.1, 2, 4, 11, 33],
    "high":   [170, 24, 8.1, 2, 0.7, 0.2, 0.2, 0.2, 0.7, 2, 8.1, 24, 170],
}
P = [comb(ROWS, k) / 2 ** ROWS for k in range(ROWS + 1)]
def rtp(t): return sum(p * v for p, v in zip(P, t))
def nice(v): return round(v, 1) if v < 10 else round(v)
if __name__ == "__main__":
    out = {}
    for name, t in SHAPES.items():
        for _ in range(4):
            k = TARGET / rtp(t)
            t = [nice(v * k) for v in t]
        # the centre slot carries 22.6% of the balls: set it exactly to land on TARGET
        c = ROWS // 2
        t[c] = round((TARGET - (rtp(t) - P[c] * t[c])) / P[c], 2)
        out[name] = t
        print("%-6s RTP %.4f  %s" % (name, rtp(t), t))
    if "--write" in sys.argv:
        with open("qml/js/PlinkoConfig.js", "w") as f:
            f.write(".pragma library\n// Generated by tools/plinkosim.py --write\nvar rows = %d\nvar tables = %s\n" % (ROWS, json.dumps(out)))
