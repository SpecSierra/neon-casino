#!/usr/bin/env python3
"""CHAIN REACTION, the cascade (connect-3) machine: rules, Monte-Carlo RTP, tuning.

    python3 tools/cascadesim.py [spins]          # report
    python3 tools/cascadesim.py --tune [spins]   # rescale pays to TARGET, write qml/js/CascadeConfig.js

Rules (mirrored in qml/js/Cascade.js):
- 5x5 grid of gems drawn from WEIGHTS.
- Any group of 3+ orthogonally connected identical gems pays BASE[gem] x SIZE[size] x the bet.
- Winning gems explode, the rest fall, new gems drop in from the top; that's a chain.
  Chain k (0-based) pays x2^k (up to x128): the multiplier doubles for as long as the chain runs.
- A spin's total is capped at MAX_WIN x the bet.
"""
import json, random, sys

TARGET = 0.95
COLS = ROWS = 5
GEMS = ["ruby", "topaz", "sapphire", "emerald", "solar", "frost", "amethyst", "nova"]
WEIGHTS = {"ruby": 16, "topaz": 15, "sapphire": 14, "emerald": 13, "solar": 12, "frost": 11, "amethyst": 10, "nova": 9}
BASE = {"ruby": 0.07, "topaz": 0.084, "sapphire": 0.105, "emerald": 0.14, "solar": 0.175, "frost": 0.21, "amethyst": 0.279, "nova": 0.557}
SIZE = {3: 1, 4: 2.5, 5: 6, 6: 12, 7: 25, 8: 50, 9: 100, 10: 200}      # 10+ uses 10
MULT_CAP = 128

def chain_mult(k):
    return min(2 ** k, MULT_CAP)
MAX_WIN = 5000

def size_factor(n):
    return SIZE[min(n, 10)]

def draw(rng):
    r = rng.random() * sum(WEIGHTS.values())
    for g in GEMS:
        r -= WEIGHTS[g]
        if r < 0:
            return g
    return GEMS[0]

def clusters(grid):
    seen = set(); out = []
    for c in range(COLS):
        for r in range(ROWS):
            if (c, r) in seen:
                continue
            g = grid[c][r]; stack = [(c, r)]; cells = []
            seen.add((c, r))
            while stack:
                x, y = stack.pop(); cells.append((x, y))
                for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
                    if 0 <= nx < COLS and 0 <= ny < ROWS and (nx, ny) not in seen and grid[nx][ny] == g:
                        seen.add((nx, ny)); stack.append((nx, ny))
            if len(cells) >= 3:
                out.append((g, cells))
    return out

def spin(rng):
    grid = [[draw(rng) for _ in range(ROWS)] for _ in range(COLS)]
    total = 0.0; k = 0
    while True:
        cl = clusters(grid)
        if not cl:
            break
        total += sum(BASE[g] * size_factor(len(cells)) for g, cells in cl) * chain_mult(k)
        gone = {cell for _, cells in cl for cell in cells}
        for c in range(COLS):
            keep = [grid[c][r] for r in range(ROWS) if (c, r) not in gone]
            grid[c] = [draw(rng) for _ in range(ROWS - len(keep))] + keep
        k += 1
    return min(total, MAX_WIN), k

def rtp(n, seed=1):
    rng = random.Random(seed); tot = 0.0; hits = 0; best = 0; chains = 0
    for _ in range(n):
        w, k = spin(rng); tot += w; hits += w > 0; best = max(best, w); chains = max(chains, k)
    return tot / n, hits / n, best, chains

def write_js():
    cfg = {"id": "cascade", "type": "cascade", "name": "CHAIN REACTION",
           "tagline": "Connect 3+ gems. They explode, more fall, and every chain stacks the multiplier.",
           "color": "#39FF88", "unlock": 3000, "volatility": 3, "music": "cascade",
           "cols": COLS, "rows": ROWS, "gems": GEMS, "symbols": GEMS, "prefix": "gem-", "weights": WEIGHTS, "base": BASE,
           "size": {str(k): v for k, v in SIZE.items()}, "maxWin": MAX_WIN, "multCap": MULT_CAP}
    with open("qml/js/CascadeConfig.js", "w") as f:
        f.write(".pragma library\n// Generated by tools/cascadesim.py --tune.\nvar machine = "
                + json.dumps(cfg, indent=1) + "\n")

if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    n = int(args[0]) if args else 200000
    if "--js" in sys.argv:
        write_js(); print("wrote qml/js/CascadeConfig.js"); sys.exit()
    if "--tune" in sys.argv:
        for _ in range(3):
            r = rtp(n)[0]
            k = TARGET / r
            for g in BASE:
                BASE[g] = round(BASE[g] * k, 3)
        write_js()
        print("BASE =", json.dumps(BASE))
    r, h, best, chains = rtp(n, seed=99)
    print("RTP %.4f  hit rate %.3f  best %.0fx  longest chain %d" % (r, h, best, chains))
