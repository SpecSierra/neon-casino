// Plays the real JS engines (qml/js) with their generated configs, bonuses included.
//   node tools/jscheck.js cascade|ways|heist [spins] [--tune]
// --tune rescales the pays in the config to 95% and recomputes the bonus-buy price.
var fs = require("fs"), path = require("path")
var JS = path.join(__dirname, "..", "qml", "js")
function load(file) { return fs.readFileSync(path.join(JS, file), "utf8").replace(".pragma library", "") }
var name = process.argv[2], N = parseInt(process.argv[3] || "500000", 10), tune = process.argv.indexOf("--tune") >= 0
var cfgFile = { cascade: "CascadeConfig.js", ways: "WaysConfig.js", heist: "HeistConfig.js" }[name]
var engine = { cascade: "Cascade.js", ways: "Ways.js", heist: "Heist.js" }[name]
eval(load(cfgFile)); eval(load(engine))
var m = machine

function bonusRound(spins) {          // returns × bet
    var won = 0, mult = 1, b = m.bonus
    if (name === "cascade") {
        while (spins > 0 && won < m.maxWin) {
            spins--; var p = play(m, 1, mult); mult = p.bonusMult; won += p.total
            if (p.cores >= b.cores) spins += b.retrigger
        }
    } else if (name === "ways") {
        while (spins > 0 && won < m.maxWin) {
            spins--; var e = evaluate(m, grid(m))
            if (e.total > 0) { won += e.total * mult; mult++ }
            if (e.scatters >= b.scatters) spins += b.retrigger
        }
    }
    return Math.min(won, m.maxWin)
}
function spin() {
    if (name === "cascade") {
        var p = play(m, 1), w = p.total, f = 0
        if (p.cores >= m.bonus.cores) { f = 1; w += bonusRound(m.bonus.spins + m.bonus.extraPerCore * (p.cores - m.bonus.cores)) }
        return [Math.min(w, m.maxWin), f]
    } else if (name === "ways") {
        var e = evaluate(m, grid(m)), w2 = e.total, f2 = 0
        if (e.scatters >= m.bonus.scatters) { f2 = 1; w2 += bonusRound(m.bonus.spins + m.bonus.extraPerScatter * (e.scatters - m.bonus.scatters)) }
        return [Math.min(w2, m.maxWin), f2]
    } else {
        var sg = spinGrid(m), lw = lines(m, sg.grid).total, locked = []
        for (var r = 0; r < m.reels; ++r) for (var c = 0; c < m.rows; ++c) if (sg.grid[r][c] === "chip") locked.push({ reel: r, row: c, value: sg.values[r][c] })
        if (locked.length >= m.trigger) return [Math.min(lw + heist(m, locked).total, m.maxWin), 1]
        return [lw, 0]
    }
}
function rtp(n) { var t = 0, f = 0; for (var i = 0; i < n; i++) { var s = spin(); t += s[0]; f += s[1] } return [t / n, n / Math.max(1, f)] }
function buyEv(n) {
    var t = 0
    for (var i = 0; i < n; i++) t += name === "heist" ? heist(m, boughtStart(m)).total : bonusRound(m.bonus.spins)
    return t / n
}
var r = rtp(N)
console.log(name, "RTP", r[0].toFixed(4), "feature 1/" + r[1].toFixed(0))
if (tune && name !== "heist") {
    for (var it = 0; it < 2; ++it) {
        var k = 0.95 / r[0]
        if (name === "cascade") for (var g in m.base) m.base[g] = Math.round(m.base[g] * k * 10000) / 10000
        else for (var s in m.pay) m.pay[s] = m.pay[s].map(function (v) { return Math.round(v * k * 10000) / 10000 })
        r = rtp(N)
        console.log("  scaled x" + k.toFixed(3) + " ->", r[0].toFixed(4))
    }
}
if (tune) {
    var ev = buyEv(Math.max(20000, N / 20))
    m.bonus.buy = Math.max(10, Math.round(ev / 0.95))
    console.log("  bonus EV " + ev.toFixed(1) + "x -> buy " + m.bonus.buy + "x")
    fs.writeFileSync(path.join(JS, cfgFile), ".pragma library\n// Generated by tools/machinesim.py " + name + " --tune, refined by tools/jscheck.js --tune.\nvar machine = "
                     + JSON.stringify(m, null, 1) + "\n")
}
