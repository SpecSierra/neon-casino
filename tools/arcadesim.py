#!/usr/bin/env python3
"""PIXEL ARCADE: slots meets bingo. Monte-Carlo RTP (greedy joker play), tuning, AcadeConfig.js.

    python3 tools/arcadesim.py [--tune] [N]

Buy a 5x5 card (column c holds 5 of the numbers 15c+1 .. 15c+15). You get SPINS spins of a
5-reel row; reel c shows a number from column c's range, a JOKER (mark any cell in column c),
a SUPER (any cell on the card), a GHOST (nothing) or a COIN (instant COIN × bet). Numbers on
the card mark themselves. At the end, complete lines (5 rows, 5 columns, 2 diagonals) pay
LADDER[lines] × bet. The joker policy here (greedy line progress) is the hint the app shows.
"""
import json, random, sys

TARGET = 0.95
SPINS = 10
P = {"number": 0.80, "joker": 0.065, "super": 0.012, "ghost": 0.115, "coin": 0.008}
COIN = 1
LADDER = [0, 0.2, 0.6, 1.8, 4, 9, 25, 60, 150, 400, 1000, 2500, 5000]
LINES = [[(r, c) for c in range(5)] for r in range(5)] + [[(r, c) for r in range(5)] for c in range(5)] \
      + [[(i, i) for i in range(5)], [(i, 4 - i) for i in range(5)]]
CELL_LINES = {(r, c): [i for i, l in enumerate(LINES) if (r, c) in l] for r in range(5) for c in range(5)}

def card(rnd):  # card[r][c]
    cols = [rnd.sample(range(15 * c + 1, 15 * c + 16), 5) for c in range(5)]
    return [[cols[c][r] for c in range(5)] for r in range(5)]

def reel(rnd, c):
    x = rnd.random()
    for k, p in P.items():
        x -= p
        if x < 0:
            return rnd.randint(15 * c + 1, 15 * c + 15) if k == "number" else k
    return "ghost"

def score(marked, cell):
    """greedy value of marking `cell`: lines through it, weighted by how far along they are"""
    v = 0.0
    for li in CELL_LINES[cell]:
        n = sum(1 for x in LINES[li] if marked[x[0]][x[1]])
        v += (n + 1) ** 3
    return v

def best_cell(marked, cols):
    best, bv = None, -1
    for c in cols:
        for r in range(5):
            if not marked[r][c]:
                v = score(marked, (r, c))
                if v > bv: bv, best = v, (r, c)
    return best

def lines_done(marked):
    return sum(1 for l in LINES if all(marked[r][c] for r, c in l))

def game(rnd, ladder=LADDER):
    cd = card(rnd)
    marked = [[False] * 5 for _ in range(5)]
    coins = 0
    for _ in range(SPINS):
        row = [reel(rnd, c) for c in range(5)]
        for c, s in enumerate(row):            # numbers first
            if isinstance(s, int):
                for r in range(5):
                    if cd[r][c] == s: marked[r][c] = True
            elif s == "coin":
                coins += COIN
        for c, s in enumerate(row):            # then jokers (column ones before supers)
            if s == "joker":
                cell = best_cell(marked, [c])
                if cell: marked[cell[0]][cell[1]] = True
        for c, s in enumerate(row):
            if s == "super":
                cell = best_cell(marked, range(5))
                if cell: marked[cell[0]][cell[1]] = True
    L = lines_done(marked)
    return ladder[L] + coins, L

def rtp(n, ladder=LADDER, seed=1):
    rnd = random.Random(seed); tot = 0; dist = [0] * 13
    for _ in range(n):
        w, L = game(rnd, ladder); tot += w; dist[L] += 1
    return tot / n, [d / n for d in dist]

def write_js(ladder):
    cfg = {"id": "arcade", "type": "arcade", "name": "PIXEL ARCADE", "color": "#39FFD2", "unlock": 10000, "volatility": 3,
           "prefix": "sym-arcade-", "music": "arcade", "symbols": ["coin", "mushroom", "ghost", "invader", "joystick", "crown"],
           "spins": SPINS, "p": P, "coin": COIN, "ladder": ladder,
           "tagline": "Slots meets bingo: 10 spins to mark a 5×5 card. Place your jokers, finish lines, climb the ladder."}
    with open("qml/js/ArcadeConfig.js", "w") as f:
        f.write(".pragma library\n// Generated by tools/arcadesim.py --tune. Edit the machine there, not here.\nvar machine = " + json.dumps(cfg, indent=1) + "\n")

if __name__ == "__main__":
    n = int(next((a for a in sys.argv[1:] if a.isdigit()), 100000))
    lad = list(LADDER)
    if "--tune" in sys.argv:
        for _ in range(6):
            r, _ = rtp(n, lad)
            if abs(r - TARGET) < 0.006: break
            k = TARGET / r
            lad = [0 if v == 0 else (round(v * k, 1) if v * k < 10 else round(v * k)) for v in lad]
        write_js(lad); print("ladder", lad)
    r, dist = rtp(n, lad, seed=7)
    print("RTP %.4f" % r, " lines:", " ".join("%d:%.3f" % (i, d) for i, d in enumerate(dist) if d > 0.0005))
