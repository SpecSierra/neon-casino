#!/usr/bin/env python3
"""VOID RUNNER: infinity reels. Monte-Carlo RTP, tuning, and qml/js/VoidConfig.js.

    python3 tools/voidsim.py [--tune] [N]

3 rows; starts with 3 reels. Wins pay ways from the left (3+ adjacent reels, wild substitutes
from reel 2 on): pay = base[s] × (length - 2) × ways. If a win reaches the last reel, a new reel
is added and spun (free); repeat up to MAX_REELS. The spin's multiplier is 1 + reels added.
Any one spin pays at most maxWin. 3+ portals anywhere: FREE SPINS, where every added reel raises a multiplier that never resets.
The engine in qml/js/Void.js mirrors this file (check with node, see tools/jscheck.js style).
"""
import json, random, sys

TARGET = 0.95
ROWS, START, MAX_REELS = 3, 3, 12
SYMS = ["comet", "moon", "ring", "rocket", "alien", "star"]
W = {"comet": 20, "moon": 18, "ring": 16, "rocket": 14, "alien": 11, "star": 7, "wild": 1.2, "portal": 2.2}
BASE = {"comet": 0.0268, "moon": 0.0375, "ring": 0.059, "rocket": 0.1072, "alien": 0.2412, "star": 0.8038}
BONUS = {"spins": 10, "retrigger": 5, "portals": 3, "maxWin": 5000}

def pick(rnd, first):
    w = dict(W)
    if first: w.pop("wild")
    tot = sum(w.values()); r = rnd.random() * tot
    for k, v in w.items():
        r -= v
        if r < 0: return k
    return "comet"

def evaluate(grid, base):
    """-> (pay in bets, reaches_last)"""
    pay, reach = 0.0, False
    n = len(grid)
    for s in SYMS:
        ways, length = 1, 0
        for col in grid:
            c = sum(1 for x in col if x == s or x == "wild")
            if c == 0: break
            ways *= c; length += 1
        if length >= 3:
            pay += base[s] * (length - 2) * ways
            if length == n: reach = True
    return pay, reach

def play(rnd, base):
    """One base or free spin: -> (pay before multiplier, reels added, portals)"""
    grid = [[pick(rnd, i == 0) for _ in range(ROWS)] for i in range(START)]
    while True:
        pay, reach = evaluate(grid, base)
        if not reach or len(grid) >= MAX_REELS: break
        grid.append([pick(rnd, False) for _ in range(ROWS)])
    portals = sum(col.count("portal") for col in grid)
    return pay, len(grid) - START, portals, grid

def spin_total(rnd, base):
    pay, added, portals, _ = play(rnd, base)
    total = min(pay * (1 + added), BONUS["maxWin"])
    fs = 0.0
    if portals >= BONUS["portals"]:
        left, mult = BONUS["spins"], 1
        while left > 0 and fs < BONUS["maxWin"]:
            left -= 1
            p, a, pt, _ = play(rnd, base)
            mult += a
            fs += p * mult
            if pt >= BONUS["portals"]: left += BONUS["retrigger"]
        fs = min(fs, BONUS["maxWin"])
    return total, fs, portals >= BONUS["portals"]

def rtp(base, n, seed=1):
    rnd = random.Random(seed)
    tb = tf = hits = 0
    for _ in range(n):
        b, f, h = spin_total(rnd, base)
        tb += b; tf += f; hits += h
    return (tb + tf) / n, tb / n, tf / n, hits / n

def write_js(base):
    cfg = {"id": "void", "type": "void", "name": "VOID RUNNER", "color": "#7A6BFF", "unlock": 4500, "volatility": 3,
           "prefix": "sym-void-", "music": "void", "symbols": SYMS, "weights": W, "base": base, "rows": ROWS, "start": START,
           "maxReels": MAX_REELS, "bonus": BONUS,
           "tagline": "Infinity reels: a win that reaches the last reel opens a new one, and every new reel adds +1× to the win."}
    with open("qml/js/VoidConfig.js", "w") as f:
        f.write(".pragma library\n// Generated by tools/voidsim.py --tune. Edit the machine there, not here.\nvar machine = " + json.dumps(cfg, indent=1) + "\n")

if __name__ == "__main__":
    n = int(next((a for a in sys.argv[1:] if a.isdigit()), 300000))
    base = dict(BASE)
    if "--tune" in sys.argv:
        for _ in range(6):
            r = rtp(base, n)[0]
            if abs(r - TARGET) < 0.006: break
            base = {k: round(v * TARGET / r, 4) for k, v in base.items()}
        write_js(base)
        print("base", base)
        import re
        src = open(__file__).read()
        open(__file__, "w").write(re.sub(r"^BASE = .*$", "BASE = " + json.dumps(base), src, count=1, flags=re.M))
    r, b, f, h = rtp(base, n, seed=99)
    print("RTP %.4f  base game %.4f  free spins %.4f  bonus 1/%.0f" % (r, b, f, 1 / max(h, 1e-9)))
