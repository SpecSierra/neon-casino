#!/usr/bin/env python3
"""Keno paytable: exact RTP per number of picks (hypergeometric), tuned to TARGET.

    python3 tools/kenosim.py           # report
    python3 tools/kenosim.py --write   # tune and write qml/js/KenoConfig.js

80 numbers, 20 drawn. PAY[k][h] = total returned per 1 bet with k picks and h hits.
"""
import json, sys
from math import comb

TARGET = 0.93
# shape of each table (relative); --write scales every row to TARGET and rounds nicely
PAY = {
    1: {1: 3},
    2: {2: 12},
    3: {2: 2, 3: 40},
    4: {2: 1, 3: 5, 4: 100},
    5: {3: 3, 4: 15, 5: 500},
    6: {3: 2, 4: 6, 5: 60, 6: 1500},
    7: {3: 1, 4: 3, 5: 20, 6: 300, 7: 5000},
    8: {4: 2, 5: 10, 6: 80, 7: 1000, 8: 10000},
    9: {4: 1, 5: 5, 6: 40, 7: 300, 8: 4000, 9: 20000},
    10: {0: 2, 5: 3, 6: 20, 7: 120, 8: 1000, 9: 5000, 10: 50000},
}

def p_hits(k, h):
    return comb(k, h) * comb(80 - k, 20 - h) / comb(80, 20)

def rtp(k):
    return sum(p_hits(k, h) * v for h, v in PAY[k].items())

def nice(v):
    if v < 10: return round(v * 2) / 2 if v < 3 else round(v)
    if v < 100: return round(v)
    if v < 1000: return round(v / 5) * 5
    return round(v / 50) * 50

if __name__ == "__main__":
    if "--write" in sys.argv:
        for k in PAY:
            for _ in range(3):
                s = TARGET / rtp(k)
                PAY[k] = {h: nice(v * s) for h, v in PAY[k].items()}
        PAY[1] = {1: 3.7}            # small tables round too coarsely; set by hand
        PAY[2] = {2: 15.5}
        cfg = {"numbers": 80, "drawn": 20, "maxPicks": 10, "pay": {str(k): {str(h): v for h, v in row.items()} for k, row in PAY.items()}}
        with open("qml/js/KenoConfig.js", "w") as f:
            f.write(".pragma library\n// Generated by tools/kenosim.py --write: total returned per 1 bet, by picks and hits.\nvar machine = "
                    + json.dumps(cfg, indent=1) + "\n")
    for k in PAY:
        print("%2d picks  RTP %.4f  " % (k, rtp(k)) + "  ".join("%d:%g" % (h, v) for h, v in sorted(PAY[k].items())))
